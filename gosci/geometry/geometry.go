package geometry

import geometry2d "github.com/KengoWada/gosci-lib/gosci/geometry/2d/shapes"

// Shape is an interface for 2D shapes that can calculate their area.
type Shape = geometry2d.Shape

// Circle represents a circle.
type Circle = geometry2d.Circle

// Rectangle represents a rectangle.
type Rectangle = geometry2d.Rectangle

// Triangle represents a triangle.
type Triangle = geometry2d.Triangle

// Square represents a square.
type Square = geometry2d.Square
